"""Deterministic PNG paths and static, file://-compatible asset metadata."""
import json
from pathlib import Path

HEADER = "// SPDX-License-Identifier: AGPL-3.0-or-later\n// Copyright (C) 2026 Javanshir Gurbanzade\n// See LICENSE and NOTICE. Generated by tools/generate_assets.py.\n"
FAMILIES = {'slime', 'skeleton', 'gargoyle', 'hound', 'cultist', 'wraith', 'reaper', 'warden', 'overlord'}


def image_path(key):
    if key.startswith('witch_'):
        group = 'characters/witch'
    elif key.startswith('demon_'):
        group = 'characters/demon'
    elif key.startswith('enemy_') or key in FAMILIES:
        group = 'characters/enemies'
    elif key.startswith('ground'):
        group = 'environments/grounds'
    elif key.startswith('prop_'):
        group = 'environments/props'
    else:
        group = 'effects'
    return f'assets/images/{group}/{key}.png'


def write_assets(root, assets, metadata):
    root = Path(root)
    manifest = {key: image_path(key) for key in sorted(assets)}
    for key, relative in manifest.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(assets[key])
    (root / 'assets/manifest.js').write_text(HEADER + 'window.NOCTURNE_ASSET_MANIFEST = Object.freeze(' + json.dumps(manifest, indent=2) + ');\n', encoding='utf-8', newline='\n')
    groups = {'atlas': ['NOCTURNE_ATLAS', 'NOCTURNE_ENEMY_ATLAS', 'NOCTURNE_RITUAL_ATLAS'],
              'packing': ['NOCTURNE_PACKING'], 'cloth': ['NOCTURNE_CLOTH'], 'animations': ['NOCTURNE_ANIMATIONS']}
    target = root / 'assets/metadata'
    target.mkdir(parents=True, exist_ok=True)
    for filename, names in groups.items():
        text = HEADER + ''.join('window.' + name + ' = Object.freeze(' + json.dumps(metadata[name], separators=(',', ':')) + ');\n' for name in names)
        (target / (filename + '.js')).write_text(text, encoding='utf-8', newline='\n')
    return manifest
